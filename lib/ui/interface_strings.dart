import 'package:flutter/widgets.dart';
import 'package:flutter/foundation.dart';

class InterfaceLocale {
  const InterfaceLocale(this.languageCode);
  final String languageCode;
}

class InterfaceStrings extends LocalizationsDelegate<InterfaceLocale> {
  const InterfaceStrings();
  @override
  bool isSupported(Locale locale) =>
      locale.languageCode == 'zh' || locale.languageCode == 'en';
  @override
  Future<InterfaceLocale> load(Locale locale) =>
      SynchronousFuture(InterfaceLocale(locale.languageCode));
  @override
  bool shouldReload(InterfaceStrings old) => false;
}

extension InterfaceText on BuildContext {
  bool get usesEnglish =>
      Localizations.of<InterfaceLocale>(this, InterfaceLocale)?.languageCode ==
      'en';

  String albumName(Album album) =>
      album.directory.split('/').any((part) => part.isNotEmpty)
      ? album.name
      : tr('共享存储根目录');

  String selectionSummary(Iterable<Photo> photos) {
    var images = 0, videos = 0;
    for (final photo in photos) {
      photo.kind == MediaKind.image ? images++ : videos++;
    }
    return tr('图片 {0}、视频 {1}', [images, videos]);
  }

  String accessDescription(MediaPermissions permissions) {
    String label(PhotoAccess access) => tr(switch (access) {
      PhotoAccess.full => '全量',
      PhotoAccess.limited => '所选项',
      PhotoAccess.denied => '未授权',
    });
    return tr('图片：{0} · 视频：{1}', [
      label(permissions.images),
      label(permissions.videos),
    ]);
  }

  // Existing domain messages and platform reasons are localized at display time.
  String domainText(String message) {
    const conflict = '无法解散，父层已有同名相册文件夹：';
    if (message.startsWith(conflict)) {
      return tr('无法解散，父层已有同名相册文件夹：{0}', [message.substring(conflict.length)]);
    }
    final restored = RegExp(
      r'^私有恢复已完成；待关联相册 (\d+) 个，待处理收藏 (\d+) 条。收藏仅保存在 PhotoTree 内。$',
    ).firstMatch(message);
    if (restored != null) {
      return tr('私有恢复已完成；待关联相册 {0} 个，待处理收藏 {1} 条。收藏仅保存在 PhotoTree 内。', [
        restored[1],
        restored[2],
      ]);
    }
    return tr(message);
  }

  String tr(String template, [List<Object?> values = const []]) {
    final text = usesEnglish ? _english[template] ?? template : template;
    if (values.isEmpty) return text;
    return text.replaceAllMapped(
      RegExp(r'\{(\d+)\}'),
      (match) => values[int.parse(match[1]!)].toString(),
    );
  }
}

